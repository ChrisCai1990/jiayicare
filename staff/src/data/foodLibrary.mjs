export function parseFoodSelections(value) {
  const values = Array.isArray(value) ? value : String(value || '').split(/[、,，;；\n]+/)
  return [...new Set(values.map(item => String(item).trim()).filter(Boolean))]
}

export function serializeFoodSelections(values) {
  return parseFoodSelections(values).join('、')
}
