const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
require('express-async-errors');
const express = require('express');
test('real isolated Mongo and authenticated HTTP care lifecycle', { skip: !process.env.PSYCHOLOGY_TEST_MONGO }, async t => {
  const uri = process.env.PSYCHOLOGY_TEST_MONGO;
  if (!/^mongodb:\/\/127\.0\.0\.1:27137\/psychology_test_[a-z0-9_]+$/.test(uri)) throw new Error('Only dedicated local test database allowed');
  process.env.JWT_SECRET = 'isolated-psychology-integration-only';
  await mongoose.connect(uri);
  const Care = require('../src/models/PsychologyCare'), Audit = require('../src/models/PsychologyAudit');
  const User = require('../src/models/User'), Admin = require('../src/models/Admin'), Tenant = require('../src/models/Tenant');
  await Care.init();
  const oid = () => new mongoose.Types.ObjectId();
  const tenant = oid(), foreign = oid(), patient = oid();
  await Tenant.collection.insertMany([{ _id: tenant, code: 'psych-test-a', name: 'A', status: 'active', serviceScope: ['staff', 'admin'] }, { _id: foreign, code: 'psych-test-b', name: 'B', status: 'active', serviceScope: ['staff', 'admin'] }]);
  const roles = ['familyDoctor', 'psychologist', 'nutritionist', 'healthManager', 'superadmin', 'familyDoctor', 'psychologist', 'psychologist'];
  const actors = roles.map((role, i) => ({ _id: oid(), role, tenantId: i === 7 ? foreign : tenant, username: `psy-test-${i}`, name: `Test ${i}`, password: 'unused', staffStatus: 'active' }));
  await Admin.collection.insertMany(actors);
  await User.collection.insertOne({ _id: patient, tenantId: tenant, name: 'Synthetic patient', phone: 'psychology-test-only', assignedFamilyDoctor: actors[0]._id });
  const Legacy = require('../src/models/ServiceRecord');
  const legacyId = oid();
  await Legacy.collection.insertOne({ _id: legacyId, patientId: patient, type: 'psychology', content: 'legacy private' });
  const app = express(); app.use(express.json()); app.use('/api/staff/psychology', require('../src/routes/psychologyCare'));
  app.use('/api/staff', require('../src/middleware/legacyPsychologyGuard'));
  app.get('/api/staff/service-records/:id', async (req, res) => res.json({ data: await Legacy.findById(req.params.id).lean() }));
  app.get('/api/staff/patients', require('../src/middleware/staffAuth'), (req, res) => res.json({ ok: true }));
  app.use((err, req, res, next) => res.status(500).json({ message: err.message }));
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  async function call(i, path = '', body, method) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/staff/${path === 'patients' || path.startsWith('service-records/') ? path : 'psychology' + path}`, { method: method || (body ? 'POST' : 'GET'), headers: { authorization: 'Bearer ' + jwt.sign({ id: actors[i]._id, type: 'admin' }, process.env.JWT_SECRET), 'content-type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, ...(await response.json()) };
  }
  assert.equal((await call(1, 'patients')).status, 403);
  assert.equal((await call(0, 'service-records/' + legacyId)).status, 200);
  for (const i of [2, 3, 4, 5, 7]) assert.equal((await call(i, 'service-records/' + legacyId)).status, 403);
  assert.equal((await call(0, 'service-records/' + legacyId, { content: 'overwrite' }, 'PUT')).status, 409);
  const legacyFilter = await require('../src/utils/psychologyLegacyAccess').legacyPsychologyFilter(actors[2]);
  assert.equal(await Legacy.countDocuments(legacyFilter), 0);
  assert.equal(await Legacy.countDocuments(await require('../src/utils/psychologyLegacyAccess').legacyPsychologyFilter(actors[0])), 1);
  assert.equal((await call(0, '', { patientId: patient, psychologistId: actors[7]._id, sharedBackground: 'foreign' })).status, 403);
  const created = await call(0, '', { patientId: patient, psychologistId: actors[1]._id, sharedBackground: 'minimum background' });
  assert.equal(created.status, 201, JSON.stringify(created)); const path = '/' + created.data._id;
  assert.equal((await call(0, '?patientId=invalid')).status, 400);
  const scoped = await call(0, '?patientId=' + patient);
  assert.equal(scoped.data.length, 1);
  assert.equal(scoped.data[0].sessions, undefined);
  assert.equal((await call(0, '?patientId=' + oid())).data.length, 0);
  assert.equal((await call(5, '?patientId=' + patient)).data.length, 0);
  assert.equal((await call(7, '?patientId=' + patient)).data.length, 0);
  assert.equal((await call(2, '?patientId=' + patient)).status, 403);

  assert.equal((await call(0, '', { patientId: patient, psychologistId: actors[1]._id, sharedBackground: 'duplicate' })).status, 409);
  for (const i of [2, 3, 4]) assert.equal((await call(i, path)).status, 403);
  assert.equal((await call(7, path)).status, 404);
  assert.equal((await call(1, path)).status, 200);
  assert.equal(await Audit.countDocuments({ careId: created.data._id }), 1);
  let result = await call(1, path, { action: 'session', version: 0, date: '2026-11-07T10:00:00+08:00', content: 'confidential formal record' });
  assert.equal(result.status, 200, JSON.stringify(result));
  const simultaneous = await Promise.all([call(0, path, { action: 'update', version: 1, status: 'paused' }), call(0, path, { action: 'update', version: 1, status: 'active' })]);
  assert.deepEqual(simultaneous.map(r => r.status).sort(), [200, 409]);
  result = await call(0, path); let version = result.data.__v;
  result = await call(0, path, { action: 'transfer', version, psychologistId: actors[6]._id, reason: 'formal handoff' });
  assert.equal(result.status, 200); assert.equal((await call(1, path)).status, 404); assert.equal((await call(6, path)).status, 200);
  await User.collection.updateOne({ _id: patient }, { $set: { assignedFamilyDoctor: actors[5]._id } });
  assert.equal((await call(0, path)).status, 404); assert.equal((await call(5, path)).status, 404);
  assert.equal((await call(5, '/takeover', { patientId: patient, reason: 'new responsible advisor' })).status, 200);
  result = await call(5, path); assert.equal(result.data.sessions[0].content, 'confidential formal record');
  assert.equal((await call(5, path, { action: 'update', version: result.data.__v, status: 'ended' })).status, 200);
  assert.equal((await call(6, path)).status, 404);
});
